-- Adds the trusted_networks table (July 2026): curated provider CIDR ranges
-- (Cloudflare/AWS/Google/Azure/...) that the engine loads every 30s alongside
-- my_whitelist/org_whitelist. A match here only quiets UNKNOWN_IP/rogue-IP
-- noise; beaconing detection stays on unless suppress_beaconing is explicitly
-- set to TRUE for that range (C2 deliberately hides on big-provider ranges,
-- so provider membership must never blanket-silence detectors).
--
-- Idempotent: CREATE TABLE IF NOT EXISTS + ON CONFLICT DO NOTHING seeds, so
-- running it twice changes nothing the second time. Note the backend runs
-- with spring.jpa.hibernate.ddl-auto=update, so Hibernate will also create
-- this table from TrustedNetworkEntry on startup — this script exists for
-- fresh installs, for the UNIQUE/NOT NULL constraints, and for the seed rows.
--
-- Apply with:
--   docker exec -i ids_db psql -U <DB_USERNAME> -d ids_db < db/trusted_networks_2026-07.sql
--
-- Seed set is a SMALL representative starter — a handful of well-known
-- ranges per provider, NOT the full published feeds (those change often;
-- syncing them automatically is future work, and the `source` column is
-- where such a job would mark its rows).

BEGIN;

CREATE TABLE IF NOT EXISTS trusted_networks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidr                TEXT NOT NULL UNIQUE,      -- e.g. '104.16.0.0/13' (IPv4 only)
    provider            TEXT NOT NULL,             -- e.g. 'Cloudflare', 'AWS', 'Custom'
    category            TEXT,                      -- free text, e.g. 'CDN', 'Cloud'
    enabled             BOOLEAN NOT NULL DEFAULT TRUE,
    suppress_beaconing  BOOLEAN NOT NULL DEFAULT FALSE,  -- see security note above
    source              TEXT NOT NULL DEFAULT 'MANUAL',
    created_at          TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMP NOT NULL DEFAULT NOW()
);

